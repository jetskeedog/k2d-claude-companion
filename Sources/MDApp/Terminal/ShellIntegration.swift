import Foundation
import SwiftTerm

/// Makes the user's shell report its working directory with OSC 7 after every prompt,
/// without modifying any of the user's dotfiles.
enum ShellIntegration {
    struct Launch {
        var executable: String
        var args: [String]
        var execName: String?
        var environment: [String]
    }

    static func launchConfiguration() -> Launch {
        let processEnv = ProcessInfo.processInfo.environment
        let shell = userShell()
        let shellName = (shell as NSString).lastPathComponent

        var env = Terminal.getEnvironmentVariables(termName: "xterm-256color", trueColor: true)
        env.append("SHELL=\(shell)")
        env.append("TERM_PROGRAM=MDApp")
        env.append("PATH=\(processEnv["PATH"] ?? "/usr/bin:/bin:/usr/sbin:/sbin")")
        for key in ["TMPDIR", "SSH_AUTH_SOCK", "LC_ALL", "LC_CTYPE"] {
            if let value = processEnv[key] { env.append("\(key)=\(value)") }
        }

        switch shellName {
        case "zsh":
            if let shimDir = writeZshShim() {
                if let userZdotdir = processEnv["ZDOTDIR"] {
                    env.append("MDAPP_ORIG_ZDOTDIR=\(userZdotdir)")
                }
                env.append("ZDOTDIR=\(shimDir.path)")
            }
            return Launch(executable: shell, args: [], execName: "-zsh", environment: env)
        case "bash":
            if let rcfile = writeBashShim() {
                return Launch(executable: shell, args: ["--rcfile", rcfile.path, "-i"], execName: "bash", environment: env)
            }
            return Launch(executable: shell, args: [], execName: "-bash", environment: env)
        default:
            return Launch(executable: shell, args: [], execName: "-" + shellName, environment: env)
        }
    }

    private static func userShell() -> String {
        if let pw = getpwuid(getuid()), let shell = pw.pointee.pw_shell {
            let path = String(cString: shell)
            if FileManager.default.isExecutableFile(atPath: path) { return path }
        }
        return ProcessInfo.processInfo.environment["SHELL"] ?? "/bin/zsh"
    }

    private static var supportDirectory: URL {
        FileManager.default.temporaryDirectory.appendingPathComponent("MDApp-shell-integration", isDirectory: true)
    }

    /// zsh only reads `.zshenv` from the shim; it immediately restores the user's ZDOTDIR so
    /// every later startup file (`.zprofile`, `.zshrc`, `.zlogin`) loads from the normal place.
    private static func writeZshShim() -> URL? {
        let dir = supportDirectory.appendingPathComponent("zsh", isDirectory: true)
        let script = #"""
        # Generated by MDApp. Restores the user's ZDOTDIR, then installs an OSC 7 cwd reporter.
        if [[ -n "${MDAPP_ORIG_ZDOTDIR+X}" ]]; then
          export ZDOTDIR="$MDAPP_ORIG_ZDOTDIR"
          unset MDAPP_ORIG_ZDOTDIR
        else
          unset ZDOTDIR
        fi
        [[ -f "${ZDOTDIR:-$HOME}/.zshenv" ]] && source "${ZDOTDIR:-$HOME}/.zshenv"

        if [[ -o interactive ]]; then
          __mdapp_report_cwd() { printf '\e]7;file://%s%s\a' "${HOST}" "${PWD}" }
          autoload -Uz add-zsh-hook
          add-zsh-hook precmd __mdapp_report_cwd
          add-zsh-hook chpwd __mdapp_report_cwd
        fi
        """#
        return write(script, to: dir.appendingPathComponent(".zshenv")) ? dir : nil
    }

    /// bash ignores `--rcfile` for login shells, so the shim emulates login startup itself.
    private static func writeBashShim() -> URL? {
        let file = supportDirectory.appendingPathComponent("bashrc")
        let script = #"""
        # Generated by MDApp. Emulates login-shell startup, then installs an OSC 7 cwd reporter.
        [ -f /etc/profile ] && . /etc/profile
        if [ -f ~/.bash_profile ]; then . ~/.bash_profile
        elif [ -f ~/.bash_login ]; then . ~/.bash_login
        elif [ -f ~/.profile ]; then . ~/.profile
        fi
        __mdapp_report_cwd() { printf '\e]7;file://%s%s\a' "${HOSTNAME}" "${PWD}"; }
        PROMPT_COMMAND="__mdapp_report_cwd${PROMPT_COMMAND:+; $PROMPT_COMMAND}"
        """#
        return write(script, to: file) ? file : nil
    }

    private static func write(_ contents: String, to url: URL) -> Bool {
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try contents.write(to: url, atomically: true, encoding: .utf8)
            return true
        } catch {
            NSLog("MDApp: failed to write shell integration \(url.path): \(error)")
            return false
        }
    }
}
